! Shared reader for the numeric bifprm.csv table generated by param_bif_set_params.
! Header names, rather than fixed column positions, define each value's meaning.
module bifprm_csv_mod
  implicit none
  private
  public :: bifprm_path, read_bifprm_csv

  type :: bifprm_path
    integer                  :: pth_id
    integer                  :: ix, iy, jx, jy
    integer                  :: ibsn, jbsn
    real                     :: length, elevtn, depth
    real                     :: start_lat, start_lon, end_lat, end_lon
    real, allocatable        :: widths(:)
    character(len=2048)      :: sort_line
  end type bifprm_path

contains

  subroutine read_bifprm_csv(filename, paths, npath, nlayer)
    character(len=*),intent(in)       :: filename
    type(bifprm_path),allocatable,intent(out) :: paths(:)
    integer,intent(out)               :: npath, nlayer
    character(len=8192)               :: line
    character(len=256)                :: header(256), fields(256)
    character(len=128)                :: width_count_text
    character(len=128)                :: legacy_format
    integer                           :: columns(14), width_columns(100)
    integer                           :: nheader, nfields, i, j, ios, unit
    integer                           :: width_index

    open(newunit=unit,file=filename,status='old',action='read',iostat=ios)
    if (ios/=0) call csv_error('cannot open '//trim(filename))
    read(unit,'(a)',iostat=ios) line
    if (ios/=0) call csv_error('cannot read header from '//trim(filename))
    call split_csv(line,header,nheader,filename)

    columns(1)=find_column(header,nheader,'pth_id',filename)
    columns(2)=find_column(header,nheader,'ix',filename)
    columns(3)=find_column(header,nheader,'iy',filename)
    columns(4)=find_column(header,nheader,'jx',filename)
    columns(5)=find_column(header,nheader,'jy',filename)
    columns(6)=find_column(header,nheader,'length',filename)
    columns(7)=find_column(header,nheader,'elevtn',filename)
    columns(8)=find_column(header,nheader,'depth',filename)
    columns(9)=find_column(header,nheader,'start_lat',filename)
    columns(10)=find_column(header,nheader,'start_lon',filename)
    columns(11)=find_column(header,nheader,'end_lat',filename)
    columns(12)=find_column(header,nheader,'end_lon',filename)
    columns(13)=find_column(header,nheader,'ibsn',filename)
    columns(14)=find_column(header,nheader,'jbsn',filename)

    nlayer=0
    width_columns=0
    do i=1,nheader
      if (index(trim(header(i)),'width_')/=1) cycle
      read(header(i)(7:),*,iostat=ios) width_index
      if (ios/=0 .or. width_index<1 .or. width_index>size(width_columns)) &
        call csv_error('invalid width column name: '//trim(header(i)))
      if (width_columns(width_index)/=0) call csv_error('duplicate column: '//trim(header(i)))
      width_columns(width_index)=i
      nlayer=max(nlayer,width_index)
    end do
    if (nlayer<1) call csv_error('bifprm.csv must contain at least width_1')
    do i=1,nlayer
      if (width_columns(i)==0) then
        write(width_count_text,'(i0)') i
        call csv_error('missing width_'//trim(width_count_text))
      endif
    end do

    ! Require exactly one definition for every standard field, including width columns.
    do i=1,size(columns)
      if (columns(i)==0) call csv_error('missing required bifprm.csv column')
    end do

    npath=0
    do
      read(unit,'(a)',iostat=ios) line
      if (ios<0) exit
      if (ios/=0) call csv_error('error reading '//trim(filename))
      if (len_trim(line)>0) npath=npath+1
    end do
    rewind(unit)
    read(unit,'(a)',iostat=ios) line
    if (ios/=0) call csv_error('cannot reread header from '//trim(filename))
    allocate(paths(npath))

    do i=1,npath
      read(unit,'(a)',iostat=ios) line
      if (ios/=0) call csv_error('unexpected end of '//trim(filename))
      call split_csv(line,fields,nfields,filename)
      if (nfields/=nheader) call csv_error('column count does not match header in '//trim(filename))
      call read_integer(fields(columns(1)),paths(i)%pth_id,filename)
      call read_integer(fields(columns(2)),paths(i)%ix,filename)
      call read_integer(fields(columns(3)),paths(i)%iy,filename)
      call read_integer(fields(columns(4)),paths(i)%jx,filename)
      call read_integer(fields(columns(5)),paths(i)%jy,filename)
      call read_real(fields(columns(6)),paths(i)%length,filename)
      call read_real(fields(columns(7)),paths(i)%elevtn,filename)
      call read_real(fields(columns(8)),paths(i)%depth,filename)
      call read_real(fields(columns(9)),paths(i)%start_lat,filename)
      call read_real(fields(columns(10)),paths(i)%start_lon,filename)
      call read_real(fields(columns(11)),paths(i)%end_lat,filename)
      call read_real(fields(columns(12)),paths(i)%end_lon,filename)
      call read_integer(fields(columns(13)),paths(i)%ibsn,filename)
      call read_integer(fields(columns(14)),paths(i)%jbsn,filename)
      if (paths(i)%pth_id/=i) call csv_error('pth_id must equal its consecutive data-row index')
      allocate(paths(i)%widths(nlayer))
      do j=1,nlayer
        call read_real(fields(width_columns(j)),paths(i)%widths(j),filename)
      end do

      ! Rebuild the legacy parameter row solely as the MPI deterministic tie-breaker.
      write(width_count_text,'(i0)') 3+nlayer
      legacy_format='(4i8,'//trim(width_count_text)//'f12.2,2f10.3,2i8)'
      write(paths(i)%sort_line,legacy_format) paths(i)%ix,paths(i)%iy,paths(i)%jx,paths(i)%jy, &
        paths(i)%length,paths(i)%elevtn,paths(i)%depth,paths(i)%widths, &
        paths(i)%start_lat,paths(i)%start_lon,paths(i)%ibsn,paths(i)%jbsn
    end do
    close(unit)
  end subroutine read_bifprm_csv

  subroutine split_csv(line,fields,nfield,filename)
    character(len=*),intent(in)        :: line, filename
    character(len=256),intent(out)     :: fields(:)
    integer,intent(out)                :: nfield
    integer                            :: i, first, last
    fields=''
    nfield=1
    first=1
    last=len_trim(line)
    do i=1,last
      if (line(i:i)/=',') cycle
      if (nfield>size(fields)) call csv_error('too many columns in '//trim(filename))
      fields(nfield)=trim(adjustl(line(first:i-1)))
      nfield=nfield+1
      first=i+1
    end do
    if (nfield>size(fields)) call csv_error('too many columns in '//trim(filename))
    fields(nfield)=trim(adjustl(line(first:last)))
    if (nfield<1) call csv_error('empty row in '//trim(filename))
  end subroutine split_csv

  integer function find_column(header,nheader,name,filename) result(column)
    character(len=*),intent(in)        :: header(:), name, filename
    integer,intent(in)                 :: nheader
    integer                            :: i, matches
    column=0
    matches=0
    do i=1,nheader
      if (trim(header(i))/=name) cycle
      column=i
      matches=matches+1
    end do
    if (matches/=1) call csv_error('required column missing or duplicated: '//trim(name)//' in '//trim(filename))
  end function find_column

  subroutine read_integer(text,value,filename)
    character(len=*),intent(in)        :: text, filename
    integer,intent(out)                :: value
    integer                            :: ios
    read(text,*,iostat=ios) value
    if (ios/=0) call csv_error('invalid integer in '//trim(filename)//': '//trim(text))
  end subroutine read_integer

  subroutine read_real(text,value,filename)
    character(len=*),intent(in)        :: text, filename
    real,intent(out)                   :: value
    integer                            :: ios
    read(text,*,iostat=ios) value
    if (ios/=0) call csv_error('invalid numeric value in '//trim(filename)//': '//trim(text))
  end subroutine read_real

  subroutine csv_error(message)
    character(len=*),intent(in)        :: message
    write(*,'(a)') 'bifprm_csv_mod: ERROR: '//trim(message)
    error stop 1
  end subroutine csv_error

end module bifprm_csv_mod
