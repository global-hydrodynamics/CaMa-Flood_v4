CHARACTER(LEN=*), INTENT(IN) :: PATH
INTEGER :: NCID,TIME_DIMID,TIME_VARID
REAL(KIND=JPRD) :: TIME(3)

TIME=(/0._JPRD,3._JPRD,6._JPRD/)
