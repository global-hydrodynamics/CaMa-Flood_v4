SUBROUTINE TEST_CALENDARS(NFAIL)
INTEGER(KIND=JPIM), INTENT(INOUT) :: NFAIL
INTEGER(KIND=JPIB) :: GREG_MARCH,NOLEAP_MARCH,GREG_JAN,NOLEAP_JAN
INTEGER(KIND=JPIM) :: IERR
CHARACTER(LEN=256) :: MESSAGE
LOGICAL :: MATCHES

CALL cf_datetime_to_minutes('gregorian',20000101_JPIM,0_JPIM,0_JPIM,GREG_JAN,IERR,MESSAGE)
CALL cf_datetime_to_minutes('gregorian',20000301_JPIM,0_JPIM,0_JPIM,GREG_MARCH,IERR,MESSAGE)
CALL ASSERT_TRUE(GREG_MARCH-GREG_JAN==60_JPIB*1440_JPIB,'Gregorian 2000 includes February 29',NFAIL)
CALL cf_datetime_to_minutes('365_day',20000101_JPIM,0_JPIM,0_JPIM,NOLEAP_JAN,IERR,MESSAGE)
CALL cf_datetime_to_minutes('365_day',20000301_JPIM,0_JPIM,0_JPIM,NOLEAP_MARCH,IERR,MESSAGE)
CALL ASSERT_TRUE(NOLEAP_MARCH-NOLEAP_JAN==59_JPIB*1440_JPIB,'365_day excludes February 29',NFAIL)
MATCHES=cf_calendar_matches_lleapyr('365_day',.FALSE.,IERR,MESSAGE)
CALL ASSERT_TRUE(MATCHES,'365_day matches LLEAPYR=.FALSE.',NFAIL)
MATCHES=cf_calendar_matches_lleapyr('gregorian',.TRUE.,IERR,MESSAGE)
CALL ASSERT_TRUE(MATCHES,'gregorian matches LLEAPYR=.TRUE.',NFAIL)
MATCHES=cf_calendar_matches_lleapyr('gregorian',.FALSE.,IERR,MESSAGE)
CALL ASSERT_TRUE(.NOT.MATCHES,'gregorian rejects LLEAPYR=.FALSE.',NFAIL)
END SUBROUTINE TEST_CALENDARS

SUBROUTINE TEST_EXTERNAL_FILE(NFAIL)
INTEGER(KIND=JPIM), INTENT(INOUT) :: NFAIL
TYPE(cf_time_axis) :: AXIS
CHARACTER(LEN=1024) :: PATH
CHARACTER(LEN=64) :: TIME_NAME
CHARACTER(LEN=32) :: ARG
CHARACTER(LEN=256) :: MESSAGE
INTEGER :: NCID,IOS
INTEGER(KIND=JPIM) :: YYYYMMDD,HOUR,EXPECTED_RECORD,RECORD,IERR

CALL GET_COMMAND_ARGUMENT(1,PATH)
CALL GET_COMMAND_ARGUMENT(2,TIME_NAME)
CALL GET_COMMAND_ARGUMENT(3,ARG)
READ(ARG,*,IOSTAT=IOS) YYYYMMDD
IF ( IOS/=0 ) ERROR STOP 'invalid YYYYMMDD argument'
CALL GET_COMMAND_ARGUMENT(4,ARG)
READ(ARG,*,IOSTAT=IOS) HOUR
IF ( IOS/=0 ) ERROR STOP 'invalid hour argument'
CALL GET_COMMAND_ARGUMENT(5,ARG)
READ(ARG,*,IOSTAT=IOS) EXPECTED_RECORD
IF ( IOS/=0 ) ERROR STOP 'invalid expected-record argument'

CALL CHECK_NC(NF90_OPEN(TRIM(PATH),NF90_NOWRITE,NCID),'open external CF file')
CALL cf_read_time_axis(NCID,TRIM(TIME_NAME),AXIS,IERR,MESSAGE)
CALL ASSERT_INT(IERR,0_JPIM,'read external CF time: '//TRIM(MESSAGE),NFAIL)
IF ( IERR==0_JPIM ) THEN
  CALL cf_find_time_record(AXIS,YYYYMMDD,HOUR,0_JPIM,RECORD,IERR,MESSAGE,.TRUE.)
  CALL ASSERT_INT(IERR,0_JPIM,'select external CF record: '//TRIM(MESSAGE),NFAIL)
  CALL ASSERT_INT(RECORD,EXPECTED_RECORD,'external CF record number',NFAIL)
  WRITE(*,'(2A)') '  units: ',TRIM(AXIS%UNITS)
  WRITE(*,'(2A)') '  calendar: ',TRIM(AXIS%CALENDAR)
  WRITE(*,'(A,I0)') '  interval [min]: ',AXIS%DT_MINUTES
  WRITE(*,'(A,I0)') '  selected record: ',RECORD
ENDIF
CALL CHECK_NC(NF90_CLOSE(NCID),'close external CF file')
END SUBROUTINE TEST_EXTERNAL_FILE

SUBROUTINE DELETE_FILE(PATH)
CHARACTER(LEN=*), INTENT(IN) :: PATH
INTEGER :: NCID,STATUS
STATUS=NF90_OPEN(PATH,NF90_WRITE,NCID)
IF ( STATUS==NF90_NOERR ) STATUS=NF90_CLOSE(NCID)
CALL EXECUTE_COMMAND_LINE('/bin/rm -f '//TRIM(PATH))
END SUBROUTINE DELETE_FILE

END PROGRAM TEST_CF_TIME
