PROGRAM TEST_CF_TIME
USE PARKIND1, ONLY: JPIM,JPIB,JPRD
USE NETCDF
USE cmf_cf_time_mod, ONLY: cf_time_axis,cf_read_time_axis,cf_find_time_record, &
                         & cf_datetime_to_minutes,cf_calendar_matches_lleapyr
IMPLICIT NONE

CHARACTER(LEN=*), PARAMETER :: DAILY_FILE='test_cf_time_daily.nc'
CHARACTER(LEN=*), PARAMETER :: HOURLY_FILE='test_cf_time_hourly.nc'
CHARACTER(LEN=*), PARAMETER :: SECONDS_FILE='test_cf_time_seconds.nc'
CHARACTER(LEN=*), PARAMETER :: MINUTES_FILE='test_cf_time_minutes.nc'
CHARACTER(LEN=*), PARAMETER :: GAP_FILE='test_cf_time_gap.nc'
CHARACTER(LEN=*), PARAMETER :: UNSUPPORTED_FILE='test_cf_time_unsupported.nc'
CHARACTER(LEN=*), PARAMETER :: TIMEZONE_FILE='test_cf_time_timezone.nc'
CHARACTER(LEN=*), PARAMETER :: VARIABLE_BOUNDS_FILE='test_cf_time_variable_bounds.nc'
INTEGER(KIND=JPIM) :: NFAIL

NFAIL=0
IF ( COMMAND_ARGUMENT_COUNT()==5 ) THEN
  CALL TEST_EXTERNAL_FILE(NFAIL)
  IF ( NFAIL/=0 ) ERROR STOP 1
  WRITE(*,'(A)') '[ALL TESTS PASSED] external CF time file'
  STOP
ENDIF
CALL CREATE_DAILY_FILE(DAILY_FILE)
CALL CREATE_HOURLY_FILE(HOURLY_FILE)
CALL CREATE_SIMPLE_FILE(SECONDS_FILE,'seconds since 2000-01-01 00:00:00','standard', &
                       & (/0._JPRD,180._JPRD,360._JPRD/))
CALL CREATE_SIMPLE_FILE(MINUTES_FILE,'minutes since 2000-01-01 00:00:00','standard', &
                       & (/0._JPRD,90._JPRD,180._JPRD/))
CALL CREATE_SIMPLE_FILE(GAP_FILE,'hours since 2000-01-01 00:00:00','standard', &
                       & (/0._JPRD,1._JPRD,3._JPRD/))
CALL CREATE_SIMPLE_FILE(UNSUPPORTED_FILE,'hours since 2000-01-01 00:00:00','360_day', &
                       & (/0._JPRD,1._JPRD,2._JPRD/))
CALL CREATE_SIMPLE_FILE(TIMEZONE_FILE,'hours since 2000-01-01 00:00 +01:00','standard', &
                       & (/0._JPRD,1._JPRD,2._JPRD/))
CALL CREATE_VARIABLE_BOUNDS_FILE(VARIABLE_BOUNDS_FILE)
CALL TEST_DAILY_BOUNDS(DAILY_FILE,NFAIL)
CALL TEST_HOURLY_RECORD(HOURLY_FILE,NFAIL)
CALL TEST_UNIT_INTERVAL(SECONDS_FILE,3_JPIB,'seconds units',NFAIL)
CALL TEST_UNIT_INTERVAL(MINUTES_FILE,90_JPIB,'minutes units',NFAIL)
CALL TEST_REJECTED_AXIS(GAP_FILE,'time gap',NFAIL)
CALL TEST_REJECTED_AXIS(UNSUPPORTED_FILE,'unsupported calendar',NFAIL)
CALL TEST_TIMEZONE(TIMEZONE_FILE,NFAIL)
CALL TEST_REJECTED_AXIS(VARIABLE_BOUNDS_FILE,'variable time-bounds width',NFAIL)
CALL TEST_CALENDARS(NFAIL)
CALL DELETE_FILE(DAILY_FILE)
CALL DELETE_FILE(HOURLY_FILE)
CALL DELETE_FILE(SECONDS_FILE)
CALL DELETE_FILE(MINUTES_FILE)
CALL DELETE_FILE(GAP_FILE)
CALL DELETE_FILE(UNSUPPORTED_FILE)
CALL DELETE_FILE(TIMEZONE_FILE)
CALL DELETE_FILE(VARIABLE_BOUNDS_FILE)

IF ( NFAIL/=0 ) THEN
  WRITE(*,'(A,I0)') '[TEST FAILED] test_cf_time: ',NFAIL
  ERROR STOP 1
ENDIF
WRITE(*,'(A)') '[ALL TESTS PASSED] test_cf_time'

CONTAINS

SUBROUTINE CHECK_NC(STATUS,LABEL)
INTEGER, INTENT(IN) :: STATUS
CHARACTER(LEN=*), INTENT(IN) :: LABEL
IF ( STATUS==NF90_NOERR ) RETURN
WRITE(*,'(3A)') '[NetCDF ERROR] ',TRIM(LABEL),': '//TRIM(NF90_STRERROR(STATUS))
ERROR STOP 1
END SUBROUTINE CHECK_NC

SUBROUTINE ASSERT_TRUE(CONDITION,LABEL,NFAIL)
LOGICAL, INTENT(IN) :: CONDITION
CHARACTER(LEN=*), INTENT(IN) :: LABEL
INTEGER(KIND=JPIM), INTENT(INOUT) :: NFAIL
IF ( CONDITION ) RETURN
NFAIL=NFAIL+1
WRITE(*,'(2A)') '[FAIL] ',TRIM(LABEL)
END SUBROUTINE ASSERT_TRUE

SUBROUTINE ASSERT_INT(ACTUAL,EXPECTED,LABEL,NFAIL)
INTEGER(KIND=JPIM), INTENT(IN) :: ACTUAL,EXPECTED
CHARACTER(LEN=*), INTENT(IN) :: LABEL
INTEGER(KIND=JPIM), INTENT(INOUT) :: NFAIL
IF ( ACTUAL==EXPECTED ) RETURN
NFAIL=NFAIL+1
WRITE(*,'(2A)') '[FAIL] ',TRIM(LABEL)
WRITE(*,'(A,I0,A,I0)') '  actual=',ACTUAL,' expected=',EXPECTED
END SUBROUTINE ASSERT_INT

SUBROUTINE CREATE_DAILY_FILE(PATH)
CHARACTER(LEN=*), INTENT(IN) :: PATH
INTEGER :: NCID,TIME_DIMID,BOUND_DIMID,TIME_VARID,BOUND_VARID
REAL(KIND=JPRD) :: TIME(3),BOUNDS(2,3)

TIME=(/0.5_JPRD,1.5_JPRD,2.5_JPRD/)
BOUNDS(:,1)=(/0._JPRD,1._JPRD/)
BOUNDS(:,2)=(/1._JPRD,2._JPRD/)
BOUNDS(:,3)=(/2._JPRD,3._JPRD/)
CALL CHECK_NC(NF90_CREATE(PATH,NF90_CLOBBER,NCID),'create daily fixture')
CALL CHECK_NC(NF90_DEF_DIM(NCID,'time',3,TIME_DIMID),'define time dimension')
CALL CHECK_NC(NF90_DEF_DIM(NCID,'bnds',2,BOUND_DIMID),'define bounds dimension')
CALL CHECK_NC(NF90_DEF_VAR(NCID,'time',NF90_DOUBLE,(/TIME_DIMID/),TIME_VARID),'define time variable')
CALL CHECK_NC(NF90_DEF_VAR(NCID,'time_bounds',NF90_DOUBLE,(/BOUND_DIMID,TIME_DIMID/),BOUND_VARID),'define bounds variable')
CALL CHECK_NC(NF90_PUT_ATT(NCID,TIME_VARID,'units','days since 1850-01-01 00:00:00'),'write units')
CALL CHECK_NC(NF90_PUT_ATT(NCID,TIME_VARID,'calendar','gregorian'),'write calendar')
CALL CHECK_NC(NF90_PUT_ATT(NCID,TIME_VARID,'bounds','time_bounds'),'write bounds attribute')
CALL CHECK_NC(NF90_ENDDEF(NCID),'end definition')
CALL CHECK_NC(NF90_PUT_VAR(NCID,TIME_VARID,TIME),'write time')
CALL CHECK_NC(NF90_PUT_VAR(NCID,BOUND_VARID,BOUNDS),'write bounds')
CALL CHECK_NC(NF90_CLOSE(NCID),'close daily fixture')
END SUBROUTINE CREATE_DAILY_FILE

