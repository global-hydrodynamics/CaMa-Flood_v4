SUBROUTINE TEST_DAILY_BOUNDS(PATH,NFAIL)
CHARACTER(LEN=*), INTENT(IN) :: PATH
INTEGER(KIND=JPIM), INTENT(INOUT) :: NFAIL
TYPE(cf_time_axis) :: AXIS
INTEGER :: NCID
INTEGER(KIND=JPIM) :: IERR,RECORD
CHARACTER(LEN=256) :: MESSAGE

CALL CHECK_NC(NF90_OPEN(PATH,NF90_NOWRITE,NCID),'open daily fixture')
CALL cf_read_time_axis(NCID,'time',AXIS,IERR,MESSAGE)
CALL ASSERT_INT(IERR,0_JPIM,'read daily CF time: '//TRIM(MESSAGE),NFAIL)
CALL ASSERT_TRUE(AXIS%HAS_BOUNDS,'daily time bounds detected',NFAIL)
CALL ASSERT_TRUE(AXIS%DT_MINUTES==1440_JPIB,'daily interval is 1440 minutes',NFAIL)
CALL cf_find_time_record(AXIS,18500101_JPIM,0_JPIM,0_JPIM,RECORD,IERR,MESSAGE)
CALL ASSERT_INT(IERR,0_JPIM,'find first daily record: '//TRIM(MESSAGE),NFAIL)
CALL ASSERT_INT(RECORD,1_JPIM,'00:00 is contained by noon-centered record 1',NFAIL)
CALL cf_find_time_record(AXIS,18500102_JPIM,0_JPIM,0_JPIM,RECORD,IERR,MESSAGE)
CALL ASSERT_INT(RECORD,2_JPIM,'next midnight selects record 2',NFAIL)
CALL cf_find_time_record(AXIS,18500101_JPIM,6_JPIM,0_JPIM,RECORD,IERR,MESSAGE,.TRUE.)
CALL ASSERT_TRUE(IERR/=0_JPIM,'reader mode rejects a start inside time bounds',NFAIL)
CALL CHECK_NC(NF90_CLOSE(NCID),'close daily fixture')
END SUBROUTINE TEST_DAILY_BOUNDS

SUBROUTINE TEST_HOURLY_RECORD(PATH,NFAIL)
CHARACTER(LEN=*), INTENT(IN) :: PATH
INTEGER(KIND=JPIM), INTENT(INOUT) :: NFAIL
TYPE(cf_time_axis) :: AXIS
INTEGER :: NCID
INTEGER(KIND=JPIM) :: IERR,RECORD
CHARACTER(LEN=256) :: MESSAGE

CALL CHECK_NC(NF90_OPEN(PATH,NF90_NOWRITE,NCID),'open hourly fixture')
CALL cf_read_time_axis(NCID,'time',AXIS,IERR,MESSAGE)
CALL ASSERT_INT(IERR,0_JPIM,'read hourly CF time: '//TRIM(MESSAGE),NFAIL)
CALL ASSERT_TRUE(.NOT.AXIS%HAS_BOUNDS,'hourly fixture has no bounds',NFAIL)
CALL ASSERT_TRUE(AXIS%DT_MINUTES==180_JPIB,'hourly interval is 180 minutes',NFAIL)
CALL cf_find_time_record(AXIS,20000101_JPIM,0_JPIM,0_JPIM,RECORD,IERR,MESSAGE)
CALL ASSERT_INT(IERR,0_JPIM,'find 2000-01-01 00:00: '//TRIM(MESSAGE),NFAIL)
CALL ASSERT_INT(RECORD,2_JPIM,'1999-12-31 21:00 file selects record 2',NFAIL)
CALL cf_find_time_record(AXIS,19991231_JPIM,22_JPIM,0_JPIM,RECORD,IERR,MESSAGE)
CALL ASSERT_TRUE(IERR/=0_JPIM,'no-bounds axis rejects a non-matching time',NFAIL)
CALL CHECK_NC(NF90_CLOSE(NCID),'close hourly fixture')
END SUBROUTINE TEST_HOURLY_RECORD

SUBROUTINE TEST_UNIT_INTERVAL(PATH,EXPECTED_MINUTES,LABEL,NFAIL)
CHARACTER(LEN=*), INTENT(IN) :: PATH,LABEL
INTEGER(KIND=JPIB), INTENT(IN) :: EXPECTED_MINUTES
INTEGER(KIND=JPIM), INTENT(INOUT) :: NFAIL
TYPE(cf_time_axis) :: AXIS
INTEGER :: NCID
INTEGER(KIND=JPIM) :: IERR
CHARACTER(LEN=256) :: MESSAGE

CALL CHECK_NC(NF90_OPEN(PATH,NF90_NOWRITE,NCID),'open unit fixture')
